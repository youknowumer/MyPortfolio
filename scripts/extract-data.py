#!/usr/bin/env python3
"""Regenerates js/data.js (structured portfolio data) from index.html.
Run:  python3 scripts/extract-data.py   — then `node scripts/validate.mjs`."""
import json, re, datetime, pathlib
from bs4 import BeautifulSoup
root = pathlib.Path(__file__).resolve().parent.parent
soup = BeautifulSoup((root/'index.html').read_text(encoding='utf8'), 'html.parser')
T = lambda el: re.sub(r'\s+', ' ', el.get_text(' ', strip=True)) if el else ''
q = lambda el, s: T(el.select_one(s)) if el else ''
MONTHS = {m: i+1 for i, m in enumerate(['jan','feb','mar','apr','may','jun','jul','aug','sep','oct','nov','dec'])}
def iso(s):
    m = re.search(r'([A-Za-z]{3})[a-z]*\.?\s+(\d{4})', s or '')
    return f"{m.group(2)}-{MONTHS[m.group(1).lower()]:02d}" if m else None

experience = []
for c in soup.select('#experience .xp-panel'):
    period = q(c, '.xp-period')
    parts = [p.strip() for p in re.split(r'[–-]', period, maxsplit=1)]
    experience.append({
        'company': q(c, '.xp-company'), 'mode': q(c, '.xp-mode'), 'role': q(c, '.xp-role'),
        'period': period, 'start': iso(parts[0]), 'end': iso(parts[1]) if len(parts) > 1 else None,
        'current': 'present' in period.lower(),
        'highlights': [T(a) for a in c.select('.xp-did-item')],
        'stack': [re.sub(r'\s*\d+%$', '', T(t)) for t in c.select('.xp-tool')]})

certs = []
for c in soup.select('#certifications .cert-card'):
    d = q(c, '.cert-date')
    certs.append({'name': q(c, '.cert-name'), 'provider': q(c, '.cert-provider'), 'issued': iso(d),
                  'issuedLabel': d, 'category': c.get('data-cat'), 'verified': bool(c.select_one('.cert-badge-v'))})

awards = [{'title': q(a, '.hon-title'), 'org': q(a, '.hon-org'), 'summary': q(a, '.hon-desc'),
           'tier': a.get('data-tier'), 'date': q(a, '.hon-date') or None}
          for a in soup.select('#awards .hon-item')]

skills = {}
for p in soup.select('.skills-panel'):
    dom = p.get('id', '').replace('tab-', '')
    skills[dom] = [{'name': q(s, '.skill-pill-name'), 'score': float(s.select_one('.skill-bar-fill')['data-w'])}
                   for s in p.select('.skill-pill') if s.select_one('.skill-bar-fill')]

projects = [{'title': q(p, 'h3, h4, .proj-title, .proj-name'), 'summary': q(p, 'p'),
             'stack': [T(t) for t in p.select('.proj-tag, .tag, .proj-tech span')]}
            for p in soup.select('#projects .proj-card')]
featured = {'title': q(soup.select_one('#projects'), '.featured-proj-title, .featured-proj h3, .featured-proj-name'),
            'subtitle': q(soup.select_one('#projects'), '.featured-proj-sub'),
            'summary': q(soup.select_one('#projects'), '.featured-proj-desc'),
            'award': q(soup.select_one('#projects'), '.featured-proj-award')}

data = {
  'meta': {'generated': datetime.date.today().isoformat(), 'schema': 2},
  'person': {'name': 'Muhammad Umer Faheem', 'handle': 'youknowumer', 'headline': 'ERP Management Trainee Officer & BI Specialist',
             'city': 'Lahore', 'country': 'PK', 'email': 'umerfaheem632@gmail.com', 'whatsapp': '+923258148564',
             'linkedin': 'https://linkedin.com/in/youknowumer', 'github': 'https://github.com/youknowumer'},
  'experience': experience, 'projects': {'featured': featured, 'others': projects},
  'certifications': certs, 'awards': awards, 'skills': skills}
out = root/'js'/'data.js'
out.write_text('/* AUTO-GENERATED by scripts/extract-data.py — single structured source for chat, palette, SEO & analytics */\n'
               'window.PORTFOLIO = Object.freeze(' + json.dumps(data, indent=1, ensure_ascii=False) + ');\n', encoding='utf8')
print({k: (len(v) if hasattr(v, '__len__') else v) for k, v in data.items()}, {k: len(v) for k, v in skills.items()})
print('projects:', [p['title'] for p in projects], '| featured:', featured['title'])
print('exp:', [(e['company'], e['start'], e['end']) for e in experience])
